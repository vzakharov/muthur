"""Drives the gate against a PR whose every fact passes, then breaks one fact
per case. GitHub is stood in for at `merge_gate.GitHub`, the gate's one seam to
the network, and the cold-cache guard by a script in the project it runs.

Run by path (`python3 .claude/merge-gate/test_merge_gate.py`), as
`scripts/vet.sh` does.
"""

