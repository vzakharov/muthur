sys.path.append(str(ROOT / ".claude" / "costs"))
from test_restart import HOUR, opening, response

ATTEST = ROOT / ".claude" / "skills" / "finalize" / "attest.md"
FOOTER = "\n\n---\n\n_Generated by [Claude Code](https://claude.ai/code)_"
ATTESTED, HEAD, MERGED = "a" * 40, "b" * 40, "c" * 40
BRANCH, NUMBER = "feat-thing", 7
TITLE = "feat: a thing"
BODY = "Why the thing.\n\nCo-authored-by: Claude <noreply@anthropic.com>"
ROW = ".claude/costs/sessions/2026-10/feat-thing/1/s.json"
STUB_SKILL = "---\ndescription: STUB — not yet hydrated.\n---\n\nBody.\n"
HYDRATED_SKILL = "---\ndescription: Dispatch the CI-only buckets.\n---\n\nBody.\n"
PULLS = f"pulls?state=open&head=owner:{BRANCH}"
CHECK_RUNS = f"commits/{HEAD}/check-runs?per_page=100&page=1"


def attestation_body(
    vet: str = "**green**",
    ci: str = "**green ([run](https://example.com/run/1))**",
    buckets: str = "**not dispatched: the diff doesn't reach them**",
    heading: str = "### Attestation",
    sha: str = ATTESTED,
) -> str:
    return (
        f"<!-- finalize-attestation {sha} -->\n\n{heading}\n\nVerified aaaaaaa (`{BRANCH}`) against `main`.\n\n"
        f"- `./scripts/vet.sh` — {vet}\n- CI on this PR — {ci}\n- CI-only buckets — {buckets}{FOOTER}"
    )


def squash_body(body: str = BODY, title_block: Optional[str] = None) -> str:
    header = "Proposed squash title/body:" if title_block is not None else "Proposed squash body:"
    blocks = f"```\n{title_block}\n```\n\n" if title_block is not None else ""
    return f"{header}\n\n{blocks}```\n{body}\n```{FOOTER}"


def comment(body: str, at: str = "2026-10-28T10:00:00Z") -> Dict[str, Any]:
    return {"id": abs(hash(body)) % 10**9, "body": body, "created_at": at, "user": {"login": "someone"}}


class FakeGitHub(gate.GitHub):
    """A PR that passes every check, held as data a case edits."""

    def __init__(self) -> None:
        super().__init__("owner/repo", "token")
        self.routes: Dict[str, Any] = {
            PULLS: [{"number": NUMBER, "draft": False}],
            f"pulls/{NUMBER}": {
                "head": {"sha": HEAD},
                "base": {"ref": "main"},
                "mergeable": True,
                "mergeable_state": "clean",
                "title": TITLE,
                "merged": False,
                "merge_commit_sha": None,
            },
            f"compare/{ATTESTED}...{HEAD}": {"status": "ahead", "files": [{"filename": ROW}]},
            f"compare/main...{HEAD}": {"behind_by": 0},
            CHECK_RUNS: {
                "total_count": 1,
                "check_runs": [{"status": "completed", "conclusion": "success"}],
            },
            f"commits/{HEAD}/status": {"statuses": []},
        }
        self.listed: Dict[str, List[Any]] = {
            f"issues/{NUMBER}/comments": [comment(attestation_body()), comment(squash_body())],
            f"pulls/{NUMBER}/reviews": [],
            f"pulls/{NUMBER}/comments": [],
        }
        self.files: Dict[str, str] = {gate.TEST_ON_GH: STUB_SKILL}
        self.refuse = False
        self.merges: List[Dict[str, Any]] = []

    def get(self, path: str) -> Any:
        return copy.deepcopy(self.routes[path])

    def pages(self, path: str) -> List[Any]:
        return copy.deepcopy(self.listed[path])

    def file(self, path: str, ref: str) -> Optional[str]:
        assert ref == HEAD
        return self.files.get(path)

    def resolution(self, number: int) -> Dict[int, bool]:
        return {}

    def previous(self, number: int, pr: Dict[str, Any]) -> None:
        return None

    def merge(self, number: int, squash: record.Squash, head: str, body_file: Path) -> bool:
        self.merges.append({"number": number, "subject": squash.subject, "body": squash.body, "head": head})
        if self.refuse:
            return False
        pr = self.routes[f"pulls/{NUMBER}"]
        pr["merged"], pr["merge_commit_sha"] = True, MERGED
        return True

    def set_comments(self, *bodies: str) -> None:
        self.listed[f"issues/{NUMBER}/comments"] = [comment(b) for b in bodies]


class GateCase(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        self.project = Path(self.tmp.name)
        self.transcript = self.project / "transcript.jsonl"
        self.github = FakeGitHub()
        self.note = gate.Note(self.project / "tmp" / "merge-gate", "sess")
        self.branch = gate.git_branch
        gate.git_branch = lambda project: BRANCH

    def tearDown(self) -> None:
        gate.git_branch = self.branch
        self.tmp.cleanup()

    def prompt(self, text: str = "/merge") -> Optional[Dict[str, Any]]:
        event = {"prompt": text, "session_id": "sess", "transcript_path": str(self.transcript)}
        return gate.on_prompt(event, self.project, self.note, lambda project: self.github)

    def assert_declines(self) -> None:
        self.assertIsNone(self.prompt())
        self.assertEqual(self.github.merges, [])


class Merges(GateCase):
    def test_a_passing_pr_is_merged_with_its_settled_title_and_body(self) -> None:
        out = self.prompt()
        assert out is not None
        self.assertEqual(out["decision"], "block")
        self.assertEqual(out["reason"], f"✅ Merged #{NUMBER} into main at ccccccc")
        self.assertIs(out["hookSpecificOutput"]["suppressOriginalPrompt"], True)
        self.assertEqual(
            self.github.merges, [{"number": NUMBER, "subject": f"{TITLE} (#{NUMBER})", "body": BODY + "\n", "head": HEAD}]
        )

    def test_a_title_block_equal_to_the_subject_passes(self) -> None:
        self.github.set_comments(attestation_body(), squash_body(title_block=f"{TITLE} (#{NUMBER})"))
        self.assertIsNotNone(self.prompt())

    def test_no_check_runs_pass_where_nothing_runs_on_a_pr(self) -> None:
        self.github.routes[CHECK_RUNS] = {"total_count": 0, "check_runs": []}
        self.github.set_comments(attestation_body(ci=record.NOTHING_RUNS), squash_body())
        self.assertIsNotNone(self.prompt())

    def test_an_identical_head_passes(self) -> None:
        self.github.routes[f"compare/{ATTESTED}...{HEAD}"] = {"status": "identical", "files": []}
        self.assertIsNotNone(self.prompt())

    def test_an_argument_is_left_to_the_agent(self) -> None:
        for text in ("/merge #7", "/merge no vet", "merge it"):
            self.assertIsNone(self.prompt(text))
        self.assertEqual(self.github.merges, [])


class Declines(GateCase):
    def test_a_draft(self) -> None:
        self.github.routes[PULLS][0]["draft"] = True
        self.assert_declines()

    def test_no_pr_or_two(self) -> None:
        for pulls in ([], [{"number": 7, "draft": False}, {"number": 8, "draft": False}]):
            self.github.routes[PULLS] = pulls
            self.assert_declines()

    def test_no_attestation_a_revoked_one_or_a_no_vet_one(self) -> None:
        none_required = attestation_body(heading="### Attestation — none required")
        revoked = attestation_body().replace(ATTESTED, "revoked")
        for bodies in ((squash_body(),), (attestation_body(), revoked, squash_body()), (none_required, squash_body())):
            self.github.set_comments(*bodies)
            self.assert_declines()

    def test_a_line_short_of_green(self) -> None:
        for line in (
            {"vet": "**red**"},
            {"ci": "**red ([run](https://example.com))**"},
            {"buckets": "**not dispatched: stopped under the two-shot rule**"},
        ):
            self.github.set_comments(attestation_body(**line), squash_body())
            self.assert_declines()

    def test_a_head_past_the_attestation_by_more_than_ledger_rows(self) -> None:
        for compare in (
            {"status": "ahead", "files": [{"filename": ROW}, {"filename": "src/app.py"}]},
            {"status": "diverged", "files": [{"filename": ROW}]},
            {"status": "ahead", "files": [{"filename": ROW}] * gate.COMPARE_FILES_CAP},
        ):
            self.github.routes[f"compare/{ATTESTED}...{HEAD}"] = compare
            self.assert_declines()

    def test_an_advanced_base(self) -> None:
        self.github.routes[f"compare/main...{HEAD}"] = {"behind_by": 1}
        self.assert_declines()

    def test_a_merge_state_short_of_clean(self) -> None:
        for mergeable, state in ((True, "blocked"), (None, "unknown"), (False, "dirty")):
            pr = self.github.routes[f"pulls/{NUMBER}"]
            pr["mergeable"], pr["mergeable_state"] = mergeable, state
            self.assert_declines()

    def test_a_check_short_of_green(self) -> None:
        for run in ({"status": "completed", "conclusion": "failure"}, {"status": "in_progress", "conclusion": None}):
            self.github.routes[CHECK_RUNS]["check_runs"] = [run]
            self.assert_declines()
        self.github.routes[CHECK_RUNS] = {"total_count": 0, "check_runs": []}
        self.github.routes[f"commits/{HEAD}/status"] = {"statuses": [{"state": "pending"}]}
        self.assert_declines()

    def test_no_checks_where_the_attestation_says_ci_ran(self) -> None:
        self.github.routes[CHECK_RUNS] = {"total_count": 0, "check_runs": []}
        self.assert_declines()

    def test_feedback_awaiting_an_answer(self) -> None:
        self.github.set_comments(attestation_body(), squash_body())
        human = comment("Wait, what about the edge case?", at="2026-10-28T11:00:00Z")
        self.github.listed[f"issues/{NUMBER}/comments"].append(human)
        self.assert_declines()

    def test_a_squash_record_that_does_not_read_back(self) -> None:
        for bodies in (
            (attestation_body(),),
            (attestation_body(), squash_body(body="Why the thing.")),
            (attestation_body(), squash_body(title_block="feat: another thing (#7)")),
        ):
            self.github.set_comments(*bodies)
            self.assert_declines()

    def test_a_title_off_the_shape(self) -> None:
        for title in ("feat(scope): a thing", "Add a thing", "feat: " + "x" * 70):
            self.github.routes[f"pulls/{NUMBER}"]["title"] = title
            self.assert_declines()

    def test_a_refused_merge(self) -> None:
        self.github.refuse = True
        self.assertIsNone(self.prompt())
        self.assertEqual(len(self.github.merges), 1)

    def test_an_error_anywhere(self) -> None:
        del self.github.routes[f"compare/main...{HEAD}"]
        with contextlib.redirect_stderr(io.StringIO()) as stderr:
            self.assertIsNone(self.prompt())
        self.assertIn("KeyError", stderr.getvalue())
        self.assertEqual(self.github.merges, [])


class Attestation(unittest.TestCase):
    def test_every_value_the_template_allows_passes(self) -> None:
        """Read off `attest.md`'s first template, so the patterns follow it."""
        template = re.search(r"```md\n(.*?)\n```", ATTEST.read_text(), re.DOTALL)
        assert template is not None
        lines = {p: line[len(p) :] for line in template.group(1).split("\n") for p in record.ALLOWED if line.startswith(p)}
        self.assertEqual(set(lines), set(record.ALLOWED))
        for prefix, value in lines.items():
            choices = re.fullmatch(r"\*\*<(.*)>\*\*", value)
            alternatives = [f"**{c}**" for c in choices.group(1).split(" | ")] if choices else [value]
            for alternative in alternatives:
                with self.subTest(alternative=alternative):
                    self.assertTrue(record.ALLOWED[prefix].fullmatch(alternative))

    def test_crlf_line_ends_read_as_lf(self) -> None:
        self.assertIsNotNone(record.attestation([attestation_body().replace("\n", "\r\n")]))


