class ColdCache(GateCase):
    def guard(self, prints: str) -> None:
        """A guard that blocks only an event the gate marked declined."""
        script = self.project / gate.COLD_CACHE
        script.parent.mkdir(parents=True)
        script.write_text(
            "import json, sys\n"
            f"if json.load(sys.stdin).get({gate.DECLINED!r}):\n"
            f"    print({prints!r})\n"
        )

    def test_a_decline_returns_the_guards_stop(self) -> None:
        self.guard(json.dumps({"decision": "block", "reason": "🪫 PROMPT CACHE EXPIRED."}))
        self.github.routes[f"compare/main...{HEAD}"] = {"behind_by": 1}
        self.assertEqual(self.prompt(), {"decision": "block", "reason": "🪫 PROMPT CACHE EXPIRED."})

    def test_a_merge_does_not_run_the_guard(self) -> None:
        self.guard(json.dumps({"decision": "block", "reason": "stop"}))
        out = self.prompt()
        assert out is not None
        self.assertTrue(out["reason"].startswith("✅ Merged"))


class AfterMerge(GateCase):
    def test_the_next_prompts_are_told_until_a_response_lands(self) -> None:
        self.transcript.write_text(json.dumps(opening(ago=2 * HOUR)) + "\n")
        self.prompt()
        for _ in range(2):
            told = self.prompt("what now?")
            assert told is not None
            self.assertIn(f"squash-merged #{NUMBER} into main at ccccccc", told["hookSpecificOutput"]["additionalContext"])
        with self.transcript.open("a") as f:
            f.write(json.dumps(response("after", ago=0, read=50_000)) + "\n")
        time.sleep(0.01)
        self.assertIsNone(self.prompt("and now?"))
        self.assertFalse(self.note.path.exists())


